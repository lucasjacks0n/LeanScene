// Part of `npm run build`: writes dist/browser/weights-data.js, the two ONNX graphs as base64
// text. The browser build imports it on first use, so a bundler has only JavaScript to deal
// with and no asset to copy or serve. About 2.1 MB; regenerated from weights/ on every build.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const at = name => new URL(`../weights/${name}`, import.meta.url);
const b64 = name => readFileSync(at(name)).toString("base64");
const out = new URL("../dist/browser/", import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(new URL("weights-data.js", out),
  `// Generated by scripts/embed_weights.mjs from weights/. Do not edit.\n` +
  `export const meta = ${readFileSync(at("meta.json"), "utf8").trim()};\n` +
  `export const features = "${b64("features.onnx")}";\n` +
  `export const head = "${b64("head.onnx")}";\n`);
